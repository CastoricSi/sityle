// The Obsidian theme (obsidian/theme.css): the fonts, sityle's tokens from
// src/si/tokens.css written out for Obsidian's .theme-light / .theme-dark (it picks
// the theme with a body class, not color-scheme), then obsidian/sityle.css, which
// maps Obsidian's variables onto them. `npm run build:obsidian`; not in the package.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const fonts = "https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@400;500&family=Noto+Sans+SC:wght@400;500;700&family=Noto+Serif+SC:wght@500;700;900&display=swap";

/** Splits "a, b" at its top-level comma: the two halves of light-dark(a, b). */
function halves(args) {
	let depth = 0;
	for (let i = 0; i < args.length; i++) {
		if (args[i] === "(") depth++;
		else if (args[i] === ")") depth--;
		else if (args[i] === "," && depth === 0) return [args.slice(0, i).trim(), args.slice(i + 1).trim()];
	}
	throw new Error(`light-dark() without two values: ${args}`);
}

/** #rrggbb → { rgb: "r, g, b", hsl: "h, s%, l%" }, for Obsidian's rgb()/hsl() variables */
function channels(hex) {
	const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
	const [rf, gf, bf] = [r / 255, g / 255, b / 255];
	const max = Math.max(rf, gf, bf);
	const min = Math.min(rf, gf, bf);
	const l = (max + min) / 2;
	const d = max - min;
	const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1));
	let h = 0;
	if (d !== 0) h = max === rf ? ((gf - bf) / d) % 6 : max === gf ? (bf - rf) / d + 2 : (rf - gf) / d + 4;
	const round = (n) => Math.round(n * 10) / 10;
	return { rgb: `${r}, ${g}, ${b}`, hsl: `${round((h * 60 + 360) % 360)}, ${round(s * 100)}%, ${round(l * 100)}%` };
}

export function obsidianTheme(tokens, mapping) {
	const base = [];
	const light = [];
	const dark = [];
	const darkOnly = new Map();
	for (const [, selector, body] of tokens.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
		const isDark = selector.includes('[data-theme="dark"]');
		if (selector.includes(":not(")) continue; // the same values again, for the system dark theme
		for (const [, name, value] of body.matchAll(/(--si-[\w-]+)\s*:\s*([^;]+);/g)) {
			if (isDark) darkOnly.set(name, value);
			else if (value.startsWith("light-dark(")) {
				const pair = halves(value.slice("light-dark(".length, -1));
				[light, dark].forEach((out, i) => {
					out.push(`${name}: ${pair[i]};`);
					if (/^#[0-9a-f]{6}$/i.test(pair[i])) {
						const { rgb, hsl } = channels(pair[i]);
						out.push(`${name}-rgb: ${rgb};`, `${name}-hsl: ${hsl};`);
					}
				});
			} else base.push(`${name}: ${value};`);
		}
	}
	for (const [name, value] of darkOnly) dark.push(`${name}: ${value};`);
	const block = (selector, lines) => `${selector} {\n${lines.map((l) => `\t${l}`).join("\n")}\n}\n`;
	return [
		"/* 丹青 sityle for Obsidian. Generated by scripts/build-obsidian.mjs from src/si/tokens.css and obsidian/sityle.css: edit those. */",
		`@import url("${fonts}");\n`,
		block("body", base),
		block(".theme-light", ["color-scheme: light;", ...light]),
		block(".theme-dark", ["color-scheme: dark;", ...dark]),
		mapping,
	].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
	writeFileSync(new URL("../obsidian/theme.css", import.meta.url), obsidianTheme(read("../src/si/tokens.css"), read("../obsidian/sityle.css")));
}
